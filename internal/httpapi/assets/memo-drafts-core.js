(function (root, factory) {
  "use strict";
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.DaynestMemoDrafts = api;
})(typeof window === "undefined" ? globalThis : window, function () {
  "use strict";
  const prefix = "daynest.memo-draft.v1:", limit = 4 * 1024 * 1024, maxRecords = 40;
  const colors = new Set(["default", "yellow", "orange", "rose", "violet", "blue", "mint", "gray"]);
  function scope(server, user) {
    try {
      const url = new URL(server);
      if (!/^https?:$/.test(url.protocol) || url.username || url.password || !/^[\w-]{1,160}$/.test(user)) return "";
      return encodeURIComponent(JSON.stringify([url.origin + url.pathname.replace(/\/+$/, ""), user]));
    } catch (_) { return ""; }
  }
  function fields(note) {
    return { title: String(note.title || ""), content: String(note.content || ""), folder_id: String(note.folder_id || ""),
      tags: Array.isArray(note.tags) ? note.tags.slice() : [], color: note.color || "default" };
  }
  function validFields(value) {
    return value && typeof value.title === "string" && value.title.length <= 320 && typeof value.content === "string" && value.content.length <= 200000 &&
      typeof value.folder_id === "string" && value.folder_id.length <= 160 && Array.isArray(value.tags) && value.tags.length <= 100 &&
      value.tags.every(tag => typeof tag === "string" && tag.length <= 1200) && colors.has(value.color);
  }
  function equal(a, b) { return JSON.stringify(fields(a)) === JSON.stringify(fields(b)); }
  // The server trims trailing body whitespace and normalizes tags when accepting edits.
  function accepted(payload, note) {
    const a = fields(payload), b = fields(note);
    a.content = a.content.replace(/[ \t\r\n]+$/, "");
    a.title = a.title.trim();
    // An empty title is generated by Go from the body. Without the accepted
    // response we cannot prove the intended title; retain the draft instead.
    if (!a.title) return false;
    a.tags = [...new Set(a.tags.map(t => t.trim().toLowerCase()).filter(Boolean))].sort();
    b.tags.sort();
    return equal(a, b);
  }
  function valid(record) {
    return record && record.version === 1 && /^[\w-]{1,100}$/.test(record.id) && /^[\w-]{1,160}$/.test(record.noteID) &&
      Number.isSafeInteger(record.generation) && record.generation > 0 && Number.isFinite(record.savedAt) &&
      typeof record.baseUpdatedAt === "string" && record.baseUpdatedAt.length <= 64 && validFields(record.base) && validFields(record.value);
  }
  function create(storage, owner) {
    if (!owner) throw Error("尚未确认草稿所属账号与服务地址。");
    const baseKey = prefix + owner + ":";
    // Generations use distinct immutable keys. A different tab can advance a
    // recovered source between our read/remove without losing its new version.
    const key = record => baseKey + record.id + ":" + record.generation;
    function list() {
      const latest = new Map(); let damaged = 0;
      for (let i = 0; i < storage.length; i++) {
        const name = storage.key(i); if (!name?.startsWith(baseKey)) continue;
        try {
          const record = JSON.parse(storage.getItem(name));
          if (valid(record) && key(record) === name) {
            if (!latest.has(record.id) || latest.get(record.id).generation < record.generation) latest.set(record.id, record);
          } else damaged++;
        }
        catch (_) { damaged++; }
      }
      return { records: [...latest.values()].sort((a, b) => b.savedAt - a.savedAt || a.id.localeCompare(b.id)), damaged };
    }
    function put(record) {
      if (!valid(record)) throw Error("草稿内容超出本机保存范围，请先导出文字。");
      const name = key(record), json = JSON.stringify(record), obsolete = []; let bytes = 0, count = 0;
      const existing = storage.getItem(name);
      if (existing !== null && existing !== json) throw Error("此草稿版本已有其他内容，请保留页面并导出文字。");
      for (let i = 0; i < storage.length; i++) {
        const k = storage.key(i); if (!k?.startsWith(prefix) || k === name) continue;
        if (k.startsWith(baseKey + record.id + ":")) {
          let prior = null; try { prior = JSON.parse(storage.getItem(k)); } catch (_) { /* Keep damaged data for explicit cleanup. */ }
          if (valid(prior) && prior.generation > record.generation) throw Error("已有更新的本机草稿，请重新查看后操作。");
          if (valid(prior) && prior.generation < record.generation) { obsolete.push(k); continue; }
        }
        bytes += 2 * (k.length + (storage.getItem(k) || "").length); count++;
      }
      if (count >= maxRecords || bytes + 2 * (name.length + json.length) > limit) throw Error("本机草稿空间已满，请先导出并清理草稿。");
      storage.setItem(name, json); // Do not evict another tab's or another account's text.
      obsolete.forEach(k => storage.removeItem(k)); // Only after the newer generation exists.
      return record;
    }
    function remove(record) {
      // Never delete a newer version, including a storage event received during a save.
      const current = storage.getItem(key(record));
      if (current === JSON.stringify(record)) storage.removeItem(key(record));
    }
    function clear() {
      const keys = [];
      for (let i = 0; i < storage.length; i++) if (storage.key(i)?.startsWith(baseKey)) keys.push(storage.key(i));
      keys.forEach(k => storage.removeItem(k));
    }
    const setting = "daynest.memo-draft-setting.v1:" + owner;
    return { list, put, remove, clear, enabled: () => storage.getItem(setting) !== "off", setEnabled: value => storage.setItem(setting, value ? "on" : "off"), owns: name => typeof name === "string" && (name.startsWith(baseKey) || name === setting) };
  }
  return { prefix, scope, fields, equal, accepted, valid, create };
});
