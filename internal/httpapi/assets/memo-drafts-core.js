(function (root, factory) {
  "use strict";
  const api = factory(typeof module === "object" && module.exports ? require("./draft-store.js") : root.DaynestDraftStore);
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.DaynestMemoDrafts = api;
})(typeof window === "undefined" ? globalThis : window, function (S) {
  "use strict";
  const prefix = "daynest.memo-draft.v1:";
  const colors = new Set(["default", "yellow", "orange", "rose", "violet", "blue", "mint", "gray"]);
  const scope = S.scope;
  function fields(note) {
    return { title: String(note.title || ""), content: String(note.content || ""), folder_id: String(note.folder_id || ""),
      tags: Array.isArray(note.tags) ? note.tags.slice() : [], color: note.color || "default" };
  }
  function validFields(value) {
    return value && typeof value.title === "string" && value.title.length <= 320 && typeof value.content === "string" && value.content.length <= 200000 &&
      typeof value.folder_id === "string" && value.folder_id.length <= 160 && Array.isArray(value.tags) && value.tags.length <= 100 &&
      value.tags.every(tag => typeof tag === "string" && tag.length <= 1200) && colors.has(value.color);
  }
  function equal(a, b) { return JSON.stringify(fields(a)) === JSON.stringify(fields(b)); }
  // The server trims trailing body whitespace and normalizes tags when accepting edits.
  function accepted(payload, note) {
    const a = fields(payload), b = fields(note);
    a.content = a.content.replace(/[ \t\r\n]+$/, "");
    a.title = a.title.trim();
    // An empty title is generated by Go from the body. Without the accepted
    // response we cannot prove the intended title; retain the draft instead.
    if (!a.title) return false;
    a.tags = [...new Set(a.tags.map(t => t.trim().toLowerCase()).filter(Boolean))].sort();
    b.tags.sort();
    return equal(a, b);
  }
  function valid(record) {
    return record && record.version === 1 && /^[\w-]{1,100}$/.test(record.id) && /^[\w-]{1,160}$/.test(record.noteID) &&
      Number.isSafeInteger(record.generation) && record.generation > 0 && Number.isFinite(record.savedAt) &&
      typeof record.baseUpdatedAt === "string" && record.baseUpdatedAt.length <= 64 && validFields(record.base) && validFields(record.value);
  }
  function create(storage, owner) {
    return S.create(storage, owner, {prefix, settingPrefix: "daynest.memo-draft-setting.v1:", valid});
  }
  return { prefix, scope, fields, equal, accepted, valid, create };
});
